#!/usr/bin/env python3
"""Turns the trained dictionaries into block_log_dictionary_data.inc (run by CMake at build time).

usage: make_dictionary_inc.py OUT.inc dictionaries.txt

dictionaries.txt has one dictionary per line:  id  first_block  file   (file relative to dictionaries.txt)
The ids are written into block logs for good: never renumber or replace a dictionary that has been used,
only add new ones (with a new id and a higher first_block).
"""
import os
import sys

out, listing = sys.argv[1], sys.argv[2]
base = os.path.dirname(os.path.abspath(listing))
entries = []
for line in open(listing):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    ident, first, name = line.split()
    entries.append((int(ident), int(first), open(os.path.join(base, name), "rb").read()))
entries.sort(key=lambda e: e[1])
assert all(0 <= e[0] <= 255 for e in entries) and len({e[0] for e in entries}) == len(entries), "bad dictionary ids"

lines = ["// Generated by scripts/blocklog/make_dictionary_inc.py - do not edit.", ""]
for ident, first, data in entries:
    lines.append("const unsigned char dictionary_%d_data[] = {" % ident)
    for i in range(0, len(data), 24):
        lines.append("   " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append("")
lines.append("const dictionary_data dictionary_table[] = {")
for ident, first, data in entries:
    lines.append("   { %d, %d, dictionary_%d_data, sizeof( dictionary_%d_data ) }," % (ident, first, ident, ident))
lines.append("   { 0, 0, nullptr, 0 }   // terminator, never used")
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out, len(entries), "dictionaries")
